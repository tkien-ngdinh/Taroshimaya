package com.taroshimaya.app.features.session_ai.domain

/**
 * Domain model representing an individual drawn card in a Tarot spread.
 * Conforms to D4 specification (KI-05) and supports F04, F09, F11, F12.
 */
data class ReadingCard(
    val positionIndex: Int,
    val positionNameVi: String,
    val positionNameEn: String,
    val cardId: String,
    val cardNameVi: String,
    val cardNameEn: String,
    val arcanaType: ArcanaType,
    val suit: CardSuit? = null,
    val isReversed: Boolean = false,
    val orientation: CardOrientation = if (isReversed) CardOrientation.REVERSED else CardOrientation.UPRIGHT,
    val drawnAtUtcIso: String,
    val normalizedX: Float = 0.5f,
    val normalizedY: Float = 0.5f,
)

enum class ArcanaType {
    MAJOR,
    MINOR,
}

enum class CardSuit {
    WANDS,
    CUPS,
    SWORDS,
    PENTACLES,
}

enum class CardOrientation {
    UPRIGHT,
    REVERSED,
}

/**
 * AI interpretation payload generated by Cloud Functions (F06 / D11).
 * Adheres to S06 disclaimer requirement and C13 Gemini flash model.
 */
data class AiInterpretation(
    val provider: String = "GEMINI_API",
    val model: String = "gemini-2.5-flash",
    val generatedAtUtcIso: String,
    val overallMessageVi: String,
    val overallMessageEn: String,
    val cardInterpretations: List<CardInterpretation>,
    val adviceVi: String,
    val adviceEn: String,
    val disclaimerText: String,
    val latencyMs: Long? = null,
    val tokensUsed: Int? = null,
)

data class CardInterpretation(
    val positionIndex: Int,
    val cardId: String,
    val interpretationVi: String,
    val interpretationEn: String,
)

/**
 * Complete Tarot Reading Session domain entity (Collection 'readings', D4).
 */
data class TarotReading(
    val id: String,
    val userId: String,
    val question: String,
    val deckId: String,
    val spreadId: String,
    val spreadNameVi: String,
    val spreadNameEn: String,
    val cards: List<ReadingCard>,
    val aiInterpretation: AiInterpretation? = null,
    val userNotes: String? = null,
    val tags: List<String> = emptyList(),
    val moodTag: String? = null,
    val accuracyRating: Int? = null,
    val ratedAtUtcIso: String? = null,
    val isFavorite: Boolean = false,
    val isOfflineSaved: Boolean = false,
    val createdAtUtcIso: String,
    val updatedAtUtcIso: String,
    val isDeleted: Boolean = false,
    val deletedAtUtcIso: String? = null,
)
