/**
 * Semantic color tokens per theme (D10, DI-03): one full Material 3 [ColorScheme] and one
 * [TaroExtendedColors] for each [TaroThemeVariant]. Text/background pairs (on* roles, and primary / secondary /
 * tertiary / error used as text on every surface tier) are checked against WCAG AA (≥ 4.5:1) in `DesignTokensTest`.
 *
 * Values listed in the reference palette (`docs/design/tokens.json`)
 * are used as they are. Roles the reference does not list are derived from the same theme's hue families:
 * `inverseSurface` = onSurface, `inverseOnSurface` = surfaceContainer, `inversePrimary` = primaryContainer,
 * `surfaceVariant` = surfaceContainerHigh, `surfaceTint` = primary. Element and status colors stay one shared
 * semantic set, so a reader recognises Fire as red and Earth as green in every theme.
 *
 * Every role is set from the Taro palette, including the Material 3 "fixed" accent roles
 * (`*Fixed`, `*FixedDim`, `on*Fixed`, `on*FixedVariant`): in all 4 themes they are a light tint with dark content,
 * so nothing falls back to the library's baseline purple. As Material 3 intends, the fixed roles do not change
 * between the default dark/light pair (Mystic Night and Moonlight share them).
 */
